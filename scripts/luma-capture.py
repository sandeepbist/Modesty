#!/usr/bin/env python3
"""Build, verify, and opt in to private Luma capture on the supported Hyprland build."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'plugins/luma-capture/plugin.cpp'
SUPPORTED_BUILD = 'c26dbf9337998ba9afcfe84050e36969bb787598'
ANCHOR = 'local fn   = require("utils.functions")'


def output(command):
    return subprocess.check_output(command, text=True, timeout=20).strip()


def build():
    version = json.loads(output(['hyprctl', 'version', '-j']))
    if version.get('commit') != SUPPORTED_BUILD:
        raise RuntimeError('This experimental plugin supports only Hyprland '+SUPPORTED_BUILD)
    flags = shlex.split(output(['pkg-config', '--cflags', '--libs', 'hyprland']))
    compiler = os.environ.get('CXX', 'c++')
    identity = SOURCE.read_bytes()+output([compiler, '--version']).encode()+repr(flags).encode()+json.dumps(version, sort_keys=True).encode()
    cache = Path(os.environ.get('XDG_CACHE_HOME', str(Path.home()/'.cache')))/'modesty/luma-capture'
    cache.mkdir(parents=True, exist_ok=True)
    target = cache/(hashlib.sha256(identity).hexdigest()[:24]+'.so')
    if not target.exists():
        with tempfile.TemporaryDirectory(prefix='build-', dir=cache) as temporary:
            result = Path(temporary)/'luma-capture.so'
            subprocess.run([compiler, '-std=c++23', '-O2', '-fPIC', '-shared', '-fno-access-control', *flags, str(SOURCE), '-o', str(result)], check=True, timeout=120)
            result.replace(target)
    return target


def paths():
    config = Path(os.environ.get('XDG_CONFIG_HOME', str(Path.home()/'.config')))
    state = Path(os.environ.get('XDG_STATE_HOME', str(Path.home()/'.local/state')))
    return (state/'modesty/luma-capture.json', config/'modesty/desktop/luma-capture.lua',
            config/'hypr/hyprland/execs.lua')


def lua_string(value):
    # Fixed-width byte escapes work in Lua, including non-ASCII and control bytes.
    return '"'+''.join(chr(b) if 32 <= b < 127 and b not in (34, 92)
                       else f'\\{b:03d}' for b in str(value).encode())+'"'


def bootstrap(marker):
    command = shlex.join([sys.executable, str(Path(__file__).resolve()), 'restore'])
    return ('-- Generated by luma-capture.py enable.\n'
            'local enabled = io.open('+lua_string(marker)+', "r")\n'
            'if enabled then\n'
            '    enabled:close()\n'
            '    hl.layer_rule({match={namespace="^modesty-command-canvas$"}, no_screen_share=true})\n'
            '    hl.layer_rule({match={namespace="^modesty-island$"}, no_screen_share=true})\n'
            '    hl.on("hyprland.start", function()\n'
            '        hl.exec_cmd('+lua_string(command)+')\n'
            '    end)\n'
            'end\n').encode()


def register(contents, script):
    matches = list(re.finditer(rb'^'+re.escape(ANCHOR.encode())+rb'(?=\r?$)', contents, re.M))
    if len(matches) != 1:
        raise RuntimeError('Installed execs.lua must contain exactly one '+ANCHOR)
    line = ('dofile('+lua_string(script)+') -- Modesty Luma capture bootstrap').encode()
    if line in contents.splitlines():
        return contents
    end = matches[0].end()
    newline = b'\r\n' if contents[end:end+2] == b'\r\n' else b'\n'
    return contents[:end]+newline+line+contents[end:]


def atomic_write(path, contents):
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = path.stat().st_mode & 0o777 if path.exists() else 0o600
    fd, temporary = tempfile.mkstemp(prefix='.luma-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(contents)
            stream.flush()
            os.fsync(stream.fileno())
            os.fchmod(stream.fileno(), mode)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def loaded():
    plugins = json.loads(output(['hyprctl', 'plugin', 'list', '-j']))
    return any(plugin.get('name') == 'luma-capture' for plugin in plugins)


def load(plugin):
    if loaded():
        if enabled_plugin(paths()[0]) == plugin:
            return False
        raise RuntimeError('A different Luma capture build is loaded. Stop capture, then disable before enabling again.')
    reply = output(['hyprctl', 'plugin', 'load', str(plugin)])
    if reply == 'ok':
        return True
    raise RuntimeError('Luma plugin load failed: '+reply)


def checked(command):
    reply = output(command)
    if reply != 'ok':
        raise RuntimeError(shlex.join(command)+' failed: '+reply)


def enabled_plugin(marker):
    if not marker.exists():
        return None
    plugin = json.loads(marker.read_text())['plugin']
    if not isinstance(plugin, str) or not Path(plugin).is_absolute():
        raise RuntimeError('Invalid Luma plugin path in '+str(marker))
    return Path(plugin)


def load_recorded(plugin, marker):
    newly_loaded = load(plugin)
    try:
        atomic_write(marker, (json.dumps({'plugin': str(plugin)})+'\n').encode())
    except OSError:
        if newly_loaded:
            checked(['hyprctl', 'plugin', 'unload', str(plugin)])
        raise


def enable():
    marker, script, execs = paths()
    original = execs.read_bytes()
    registered = register(original, script)
    plugin = build()
    load_recorded(plugin, marker)
    try:
        atomic_write(script, bootstrap(marker))
        if registered != original:
            atomic_write(execs, registered)
        checked(['hyprctl', 'reload'])
    except (OSError, subprocess.SubprocessError, RuntimeError) as error:
        raise RuntimeError('Enable incomplete; Luma capture remains loaded. Run '+
                           shlex.join([sys.executable, str(Path(__file__).resolve()), 'disable'])+
                           ' to undo it. '+str(error)) from error
    return plugin


def restore():
    marker, _, _ = paths()
    if enabled_plugin(marker) is None:
        return None
    plugin = build()
    load_recorded(plugin, marker)
    return plugin


def disable():
    marker, _, _ = paths()
    plugin = enabled_plugin(marker)
    if plugin is not None:
        command = ['hyprctl', 'plugin', 'unload', str(plugin)]
        reply = output(command)
        if reply not in ('ok', 'plugin not loaded'):
            raise RuntimeError(shlex.join(command)+' failed: '+reply)
        marker.unlink()
    checked(['hyprctl', 'reload'])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('build', 'test', 'status', 'enable', 'disable', 'restore'))
    args = parser.parse_args()
    try:
        if args.command == 'status':
            print(json.dumps({'experimental': True, 'supportedBuild': SUPPORTED_BUILD,
                              'supported': json.loads(output(['hyprctl', 'version', '-j'])).get('commit') == SUPPORTED_BUILD,
                              'enabled': paths()[0].exists(), 'loaded': loaded()}))
        elif args.command == 'disable':
            disable()
            print('Luma capture disabled')
        elif args.command in ('enable', 'restore'):
            plugin = enable() if args.command == 'enable' else restore()
            print(plugin if plugin else 'Luma capture disabled; restore skipped')
        else:
            plugin = build()
            if args.command == 'build':
                print(plugin)
            else:
                subprocess.run(['python3', str(ROOT/'tests/luma-capture-live.py'), '--plugin', str(plugin)], check=True)
    except (OSError, subprocess.SubprocessError, ValueError, KeyError, RuntimeError) as error:
        parser.exit(1, str(error)+'\n')


if __name__ == '__main__':
    main()
